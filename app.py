
import streamlit as st

st.set_page_config(
    page_title="TPN Simulator",
    page_icon="☢️",
    layout="wide",
)

st.title("☢️ TPN Simulator")

st.subheader(
    "Моделирование переноса нейтронов "
    "методом Монте-Карло"
)

st.markdown("""
Данное приложение предназначено для численного
исследования процессов взаимодействия нейтронов
с веществом с использованием метода Монте-Карло.

Реализованы две независимые вычислительные модели.
""")

st.divider()

col1, col2 = st.columns(2)

with col1:
    st.markdown("### 1. Свободный пробег нейтронов")

    st.markdown("""
    Исследование экспоненциального распределения
    длины свободного пробега.

    Основные задачи:
    - Генерация случайных длин пробега.
    - Расчёт вероятности прохождения расстояния
      без взаимодействия.
    - Сравнение с аналитическим решением.
    """)

with col2:
    st.markdown("### 2. Бериллиевая сфера")

    st.markdown("""
    Моделирование радиационного захвата нейтронов
    в сферической бериллиевой мишени.

    Основные задачи:
    - Моделирование шести нейтронных пучков.
    - Расчёт вероятности радиационного захвата.
    - Исследование пространственного распределения
      нейтронного потока.
    """)

st.divider()

st.markdown("### Технологии")

st.write(
    "Python · NumPy · Matplotlib · Streamlit"
)

st.caption(
    "Выполните выбор модели в боковой панели приложения."
)
